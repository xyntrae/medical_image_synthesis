#!/usr/bin/env python
"""Seeded external wrapper around the unchanged baseline scripts.

Runs, without editing them:
  1. data_preprocessing.py  (reads data/brain_tumor, data/non_brain_tumor,
                              writes data/*.npy, relative to its working dir)
  2. model_training.py      (50 epochs, batch 64, Adam 1e-4, noise dim 100,
                              writes generator_w.weights.h5 to its working dir)
then exports synthetic samples from the trained generator.

How the unchanged scripts are pointed at your data: the wrapper creates
<output>/work/data/ and places two directory links in it (a junction on
Windows, a symlink elsewhere) named brain_tumor and non_brain_tumor that point
at the folders inside --data-dir. The scripts run with <output>/work as their
working directory, so the .npy files and weights land in <output>/work and
nothing is written into --data-dir. The links are removed when the run ends.

Seeding: each stage runs in a child Python process that first sets
PYTHONHASHSEED, Python random, NumPy and TensorFlow seeds
(tf.keras.utils.set_random_seed), enables TF op determinism
(tf.config.experimental.enable_op_determinism, TF_DETERMINISTIC_OPS=1,
TF_CUDNN_DETERMINISTIC=1, TF_ENABLE_ONEDNN_OPTS=0), and then executes the original script with runpy.
No baseline source file is modified.

Smoke tests: --smoke-epochs N overrides the hard-coded epochs=50 at runtime
by wrapping tf.keras.Model.fit in the child process. This is for pipeline
smoke tests only; results are labelled smoke_test everywhere.

Outputs in --output-dir:
  stdout.log            combined stdout/stderr of all stages
  losses.csv            per-epoch gen_loss and disc_loss parsed from stdout
  run_summary.json      seeds, versions, devices, wall times, GPU memory, flags
  samples/SYNTHETIC_grid_8x8.png          8x8 grid with a SYNTHETIC banner
  samples/synthetic_sample_XXXX.png       individual samples (PNG text chunk
                                          marks them as synthetic)
  SYNTHETIC_OUTPUTS_README.txt
  work/                 intermediate .npy files and generator weights

All generated images are synthetic research artifacts, not real scans, and
have no clinical validity.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import os
import platform
import re
import shutil
import subprocess
import sys
import threading
import time
from datetime import datetime, timezone
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
CLASSES = ("brain_tumor", "non_brain_tumor")
BASELINE_FILES = ["data_preprocessing.py", "model_training.py", "models/generator.py",
                  "models/discriminator.py", "utils/image_utils.py", "utils/data_loader.py"]
WEIGHTS_NAME = "generator_w.weights.h5"
NOISE_DIM = 100
SYNTHETIC_NOTE = ("SYNTHETIC IMAGE generated by an unconditional GAN baseline. Research artifact only. "
                  "Not a real scan. No clinical validity.")
ENV_MARK = "[run_baseline] ENV "

EPOCH_RE = re.compile(r"Epoch (\d+)/(\d+)")
GEN_RE = re.compile(r"gen_loss: ([-+0-9.eE]+|nan|inf)")
DISC_RE = re.compile(r"disc_loss: ([-+0-9.eE]+|nan|inf)")
TIME_RE = re.compile(r"\] - (\d+(?:\.\d+)?m?s) ")


# ----------------------------------------------------------------------------
# Log parsing (pure function, unit tested without TensorFlow)
# ----------------------------------------------------------------------------
def parse_keras_log(text: str):
    """Return a list of dicts, one per epoch, with the last gen/disc loss printed.

    Keras prints running values on progress-bar updates separated by '\\r' and
    the final value for the epoch on the last update. We keep the last value
    seen within each epoch, which is the value Keras displays at epoch end.
    """
    rows = {}
    current = None
    for line in re.split(r"[\r\n]+", text):
        m = EPOCH_RE.search(line)
        if m and "loss" not in line:
            current = int(m.group(1))
            rows.setdefault(current, {"epoch": current, "total_epochs": int(m.group(2)),
                                      "gen_loss": None, "disc_loss": None, "epoch_time": None})
            continue
        if current is None:
            continue
        g, d = GEN_RE.search(line), DISC_RE.search(line)
        if g:
            rows[current]["gen_loss"] = float(g.group(1))
        if d:
            rows[current]["disc_loss"] = float(d.group(1))
        t = TIME_RE.search(line)
        if t and (g or d):
            rows[current]["epoch_time"] = t.group(1)
    return [rows[k] for k in sorted(rows)]


# ----------------------------------------------------------------------------
# GPU memory sampling
# ----------------------------------------------------------------------------
class GpuSampler(threading.Thread):
    """Polls nvidia-smi for device memory.used. Whole-device figure (all processes)."""

    def __init__(self, interval=1.0):
        super().__init__(daemon=True)
        self.interval = interval
        self.exe = shutil.which("nvidia-smi")
        self.samples = []
        self.error = None
        self._stop = threading.Event()

    def query(self):
        out = subprocess.run([self.exe, "--query-gpu=index,name,memory.used,memory.total",
                              "--format=csv,noheader,nounits"], capture_output=True, text=True, timeout=10)
        rows = []
        for line in out.stdout.strip().splitlines():
            parts = [p.strip() for p in line.split(",")]
            if len(parts) == 4:
                rows.append({"index": int(parts[0]), "name": parts[1],
                             "used_mib": int(parts[2]), "total_mib": int(parts[3])})
        return rows

    def run(self):
        if not self.exe:
            return
        while not self._stop.is_set():
            try:
                self.samples.append((time.time(), self.query()))
            except Exception as e:  # keep training going even if polling fails
                self.error = f"{type(e).__name__}: {e}"
            self._stop.wait(self.interval)

    def stop(self):
        self._stop.set()

    def summary(self, baseline):
        if not self.exe:
            return {"available": False, "note": "nvidia-smi not found"}
        peak = {}
        for _, rows in self.samples:
            for r in rows:
                peak[r["index"]] = max(peak.get(r["index"], 0), r["used_mib"])
        base = {r["index"]: r["used_mib"] for r in (baseline or [])}
        return {
            "available": True,
            "samples": len(self.samples),
            "interval_s": self.interval,
            "devices": [{"index": r["index"], "name": r["name"], "total_mib": r["total_mib"],
                         "used_before_run_mib": base.get(r["index"]),
                         "peak_used_during_run_mib": peak.get(r["index"]),
                         "peak_minus_before_mib": (peak[r["index"]] - base[r["index"]])
                         if r["index"] in peak and r["index"] in base else None}
                        for r in (baseline or [])],
            "note": "nvidia-smi memory.used is whole-device usage including other processes",
            "error": self.error,
        }


# ----------------------------------------------------------------------------
# Child process: seeding then run a stage
# ----------------------------------------------------------------------------
def _child_main(args) -> int:
    import random
    seed = args.seed
    random.seed(seed)
    import numpy as np
    np.random.seed(seed)
    import tensorflow as tf
    tf.keras.utils.set_random_seed(seed)
    det = None
    try:
        tf.config.experimental.enable_op_determinism()
        det = True
    except Exception as e:  # report, do not hide
        det = f"failed: {type(e).__name__}: {e}"
    try:
        import keras
        keras_version = keras.__version__
    except Exception:
        keras_version = None
    env = {
        "stage": args.child_stage, "seed": seed, "python": platform.python_version(),
        "numpy": np.__version__, "tensorflow": tf.__version__, "keras": keras_version,
        "tf_built_with_cuda": tf.test.is_built_with_cuda(),
        "tf_gpus": [d.name for d in tf.config.list_physical_devices("GPU")],
        "op_determinism": det,
        "env": {k: os.environ.get(k) for k in ("PYTHONHASHSEED", "TF_DETERMINISTIC_OPS",
                                               "TF_CUDNN_DETERMINISTIC", "TF_FORCE_GPU_ALLOW_GROWTH", "TF_ENABLE_ONEDNN_OPTS",
                                               "CUDA_VISIBLE_DEVICES")},
    }
    print(ENV_MARK + json.dumps(env), flush=True)
    sys.path.insert(0, str(REPO))

    if args.child_stage == "preprocess":
        import runpy
        runpy.run_path(str(REPO / "data_preprocessing.py"), run_name="__main__")
    elif args.child_stage == "train":
        if args.smoke_epochs:
            orig_fit = tf.keras.Model.fit

            def fit(self, *a, **kw):
                if "epochs" not in kw:
                    raise RuntimeError("smoke override expected fit(..., epochs=...) as keyword")
                print(f"[run_baseline] SMOKE TEST: overriding epochs {kw['epochs']} -> {args.smoke_epochs}",
                      flush=True)
                kw["epochs"] = args.smoke_epochs
                return orig_fit(self, *a, **kw)

            tf.keras.Model.fit = fit
        import runpy
        runpy.run_path(str(REPO / "model_training.py"), run_name="__main__")
    elif args.child_stage == "export":
        _export_samples(args, tf, np)
    return 0


def _export_samples(args, tf, np):
    from PIL import Image, ImageDraw
    from PIL.PngImagePlugin import PngInfo
    from models.generator import build_generator

    out = Path(args.child_out)
    sdir = out / "samples"
    sdir.mkdir(parents=True, exist_ok=True)
    gen = build_generator(noise_dim=NOISE_DIM)
    gen.load_weights(str(Path.cwd() / WEIGHTS_NAME))
    n = max(64, args.num_samples)
    noise = np.random.default_rng(args.seed + 1).standard_normal((n, NOISE_DIM)).astype("float32")
    imgs = gen(noise, training=False).numpy()  # (n, 128, 128, 1), sigmoid [0, 1]
    imgs = (np.clip(imgs[..., 0], 0, 1) * 255).round().astype("uint8")

    tag = "smoke_test" if args.smoke_epochs else "full_baseline"
    def meta():
        m = PngInfo()
        m.add_text("Synthetic", "true")
        m.add_text("Description", SYNTHETIC_NOTE)
        m.add_text("RunType", tag)
        m.add_text("Seed", str(args.seed))
        return m

    for i in range(args.num_samples):
        Image.fromarray(imgs[i], mode="L").save(sdir / f"synthetic_sample_{i:04d}.png", pnginfo=meta())

    h, w = imgs.shape[1:]
    gap, banner = 2, 28
    grid = Image.new("L", (8 * w + 9 * gap, banner + 8 * h + 9 * gap), 0)
    for k in range(64):
        r, c = divmod(k, 8)
        grid.paste(Image.fromarray(imgs[k], mode="L"), (gap + c * (w + gap), banner + gap + r * (h + gap)))
    d = ImageDraw.Draw(grid)
    d.rectangle([0, 0, grid.width, banner - 1], fill=255)
    d.text((6, 3), f"SYNTHETIC ({tag}) - GAN samples, research artifact, not real scans, no clinical validity",
           fill=0)
    d.text((6, 15), f"seed {args.seed}", fill=0)
    grid.save(sdir / "SYNTHETIC_grid_8x8.png", pnginfo=meta())
    print(f"[run_baseline] exported {args.num_samples} samples and 8x8 grid to {sdir}", flush=True)


# ----------------------------------------------------------------------------
# Parent process
# ----------------------------------------------------------------------------
def _make_dir_link(target: Path, link: Path):
    if os.name == "nt":
        import _winapi
        _winapi.CreateJunction(str(target), str(link))
    else:
        os.symlink(str(target), str(link), target_is_directory=True)


def _remove_dir_link(link: Path):
    try:
        os.readlink(str(link))  # raises if not a link/junction
    except (OSError, ValueError):
        return False
    if os.name == "nt":
        os.rmdir(str(link))  # removes the junction only, never the target
    else:
        os.unlink(str(link))
    return True


def _sha256(p: Path):
    return hashlib.sha256(p.read_bytes()).hexdigest() if p.is_file() else None


def _git(*a):
    try:
        return subprocess.run(["git", "-C", str(REPO), *a], capture_output=True, text=True,
                              timeout=20).stdout.strip()
    except Exception:
        return None


def _run_stage(name, cmd, cwd, env, log_fh, echo):
    log_fh.write(f"\n===== [run_baseline] stage {name}: {' '.join(cmd)}\n")
    log_fh.flush()
    t0 = time.perf_counter()
    proc = subprocess.Popen(cmd, cwd=str(cwd), env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    chunks = []
    while True:
        b = proc.stdout.read1(65536) if hasattr(proc.stdout, "read1") else proc.stdout.read(4096)
        if not b:
            break
        s = b.decode("utf-8", errors="replace")
        chunks.append(s)
        log_fh.write(s)
        log_fh.flush()
        if echo:
            sys.stdout.write(s)
            sys.stdout.flush()
    rc = proc.wait()
    return rc, time.perf_counter() - t0, "".join(chunks)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        prog="run_baseline.py",
        description=("Seeded wrapper that runs the unchanged baseline (data_preprocessing.py then "
                     "model_training.py), logs per-epoch losses to CSV, records wall time and GPU "
                     "memory, and exports SYNTHETIC sample images. See docs/BASELINE_USAGE.md."),
    )
    ap.add_argument("--data-dir", type=Path, help="folder containing brain_tumor/ and non_brain_tumor/")
    ap.add_argument("--output-dir", type=Path, help="new or empty folder for all outputs (outside --data-dir)")
    ap.add_argument("--seed", type=int, default=42, help="seed for Python, NumPy and TensorFlow (default: 42)")
    ap.add_argument("--smoke-epochs", type=int, default=None,
                    help="SMOKE TESTS ONLY: override the baseline's 50 epochs with this number")
    ap.add_argument("--num-samples", type=int, default=64, help="individual sample PNGs to export (default: 64)")
    ap.add_argument("--python", default=sys.executable,
                    help="Python interpreter with TensorFlow for the child stages (default: this one)")
    ap.add_argument("--cpu", action="store_true", help="hide GPUs from TensorFlow (CUDA_VISIBLE_DEVICES=-1)")
    ap.add_argument("--no-memory-growth", action="store_true",
                    help="do not set TF_FORCE_GPU_ALLOW_GROWTH=true (TF then reserves most GPU memory up front)")
    ap.add_argument("--keep-onednn", action="store_true",
                    help="do not set TF_ENABLE_ONEDNN_OPTS=0 (oneDNN CPU kernels may reduce run-to-run reproducibility)")
    ap.add_argument("--gpu-poll-interval", type=float, default=1.0, help="nvidia-smi poll interval in s")
    ap.add_argument("--delete-intermediate", action="store_true",
                    help="delete work/data/*.npy (array copies of your data) after a successful run")
    ap.add_argument("--quiet", action="store_true", help="do not echo child output to the console")
    # internal: child stage entry point
    ap.add_argument("--child-stage", choices=["preprocess", "train", "export"], help=argparse.SUPPRESS)
    ap.add_argument("--child-out", help=argparse.SUPPRESS)
    args = ap.parse_args(argv)

    if args.child_stage:
        return _child_main(args)
    if args.data_dir is None or args.output_dir is None:
        ap.error("--data-dir and --output-dir are required")
    if args.smoke_epochs is not None and args.smoke_epochs < 1:
        ap.error("--smoke-epochs must be >= 1")
    if args.num_samples < 1:
        ap.error("--num-samples must be >= 1")

    data_dir = args.data_dir.resolve()
    out = args.output_dir.resolve()
    for c in CLASSES:
        if not (data_dir / c).is_dir():
            ap.error(f"missing class folder: {data_dir / c}")
    if out == data_dir or data_dir in out.parents:
        ap.error("--output-dir must not be inside --data-dir")
    if out.exists() and any(out.iterdir()):
        ap.error(f"--output-dir must be new or empty: {out}")
    missing = [f for f in BASELINE_FILES if not (REPO / f).is_file()]
    if missing:
        ap.error(f"baseline files not found in {REPO}: {missing}")

    run_type = "smoke_test" if args.smoke_epochs else "full_baseline"
    work = out / "work"
    (work / "data").mkdir(parents=True)
    links = []
    summary = {
        "run_type": run_type,
        "label": ("SMOKE TEST (reduced epochs, pipeline check only, not evidence of model quality)"
                  if args.smoke_epochs else "Full baseline run (unchanged 50-epoch configuration)"),
        "started_utc": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S"),
        "seed": args.seed,
        "smoke_epochs": args.smoke_epochs,
        "baseline_epochs_in_source": 50,
        "num_samples": args.num_samples,
        "data_dir_name": data_dir.name,
        "platform": platform.platform(),
        "parent_python": platform.python_version(),
        "child_python_executable": args.python,
        "git_head": _git("rev-parse", "HEAD"),
        "git_baseline_files_modified": _git("status", "--porcelain", "--", *BASELINE_FILES) or "",
        "baseline_file_sha256": {f: _sha256(REPO / f) for f in BASELINE_FILES},
        "stages": {},
    }

    env = dict(os.environ)
    env.update({"PYTHONHASHSEED": str(args.seed), "TF_DETERMINISTIC_OPS": "1", "TF_CUDNN_DETERMINISTIC": "1",
                "PYTHONUNBUFFERED": "1", "PYTHONDONTWRITEBYTECODE": "1", "PYTHONIOENCODING": "utf-8"})
    if not args.no_memory_growth:
        env["TF_FORCE_GPU_ALLOW_GROWTH"] = "true"
    if args.cpu:
        env["CUDA_VISIBLE_DEVICES"] = "-1"
    if not args.keep_onednn:
        env["TF_ENABLE_ONEDNN_OPTS"] = "0"

    sampler = GpuSampler(args.gpu_poll_interval)
    gpu_before = None
    if sampler.exe:
        try:
            gpu_before = sampler.query()
        except Exception as e:
            sampler.error = f"{type(e).__name__}: {e}"
    rc_all = 0
    t_total = time.perf_counter()
    log_path = out / "stdout.log"
    train_text = ""
    try:
        for c in CLASSES:
            link = work / "data" / c
            _make_dir_link(data_dir / c, link)
            links.append(link)
        sampler.start()
        with open(log_path, "w", encoding="utf-8") as log_fh:
            base_cmd = [args.python, "-u", str(Path(__file__).resolve()), "--seed", str(args.seed),
                        "--child-out", str(out), "--num-samples", str(args.num_samples)]
            if args.smoke_epochs:
                base_cmd += ["--smoke-epochs", str(args.smoke_epochs)]
            for stage in ("preprocess", "train", "export"):
                rc, dt, text = _run_stage(stage, base_cmd + ["--child-stage", stage], work, env, log_fh,
                                          not args.quiet)
                envline = next((l for l in text.splitlines() if l.startswith(ENV_MARK)), None)
                summary["stages"][stage] = {"returncode": rc, "wall_time_s": round(dt, 3),
                                            "child_env": json.loads(envline[len(ENV_MARK):]) if envline else None}
                if stage == "preprocess" and rc == 0:
                    try:
                        import numpy as np
                        summary["array_shapes"] = {
                            p.name: list(np.load(p, mmap_mode="r").shape)
                            for p in sorted((work / "data").glob("*.npy"))}
                    except Exception as e:
                        summary["array_shapes"] = f"unavailable: {type(e).__name__}"
                if stage == "train":
                    train_text = text
                if rc != 0:
                    rc_all = rc
                    break
    finally:
        sampler.stop()
        for link in links:
            _remove_dir_link(link)
        summary["total_wall_time_s"] = round(time.perf_counter() - t_total, 3)

    rows = parse_keras_log(train_text)
    with open(out / "losses.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=["epoch", "total_epochs", "gen_loss", "disc_loss", "epoch_time"])
        w.writeheader()
        w.writerows(rows)
    summary["epochs_parsed"] = len(rows)
    summary["final_losses"] = rows[-1] if rows else None
    summary["gpu_memory"] = sampler.summary(gpu_before)
    summary["weights_file"] = str((work / WEIGHTS_NAME).relative_to(out)) if (work / WEIGHTS_NAME).exists() else None
    summary["returncode"] = rc_all
    if rc_all == 0 and args.delete_intermediate:
        for p in (work / "data").glob("*.npy"):
            p.unlink()
        summary["intermediate_npy_deleted"] = True
    (out / "run_summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    (out / "SYNTHETIC_OUTPUTS_README.txt").write_text(
        SYNTHETIC_NOTE + "\n\nEvery image under samples/ was produced by the generator. None of them is a "
        "real scan. Run type: " + run_type + ".\n", encoding="utf-8")
    print(f"\n[run_baseline] {run_type} finished with return code {rc_all}; "
          f"total wall time {summary['total_wall_time_s']} s; {len(rows)} epochs parsed; outputs in {out}")
    return rc_all


if __name__ == "__main__":
    raise SystemExit(main())
