import argparse
import os
import tkinter as tk
from tkinter import Canvas, messagebox
from PIL import Image, ImageTk
import tensorflow as tf
import numpy as np
from config import NOISE_DIM
from models.generator import build_generator

DEFAULT_WEIGHTS = 'generator_w.weights.h5'
SYNTHETIC_LABEL = ("SYNTHETIC IMAGE generated by a GAN for research only.\n"
                   "Not a real scan. Not for clinical use.")


def to_uint8_image(generated_images):
    """Convert one generator output of shape (1, 128, 128, 1) in [0, 1] to a 128x128 uint8 array."""
    generated_images = np.asarray(generated_images).reshape(128, 128)
    return (generated_images * 255).astype(np.uint8)


def load_generator(weights_path):
    """Build the generator and load weights. Raises FileNotFoundError if the file is missing."""
    if not os.path.isfile(weights_path):
        raise FileNotFoundError(weights_path)
    generator = build_generator()
    generator.load_weights(weights_path)
    return generator


class ImageGeneratorApp:
    def __init__(self, master, weights_path=DEFAULT_WEIGHTS, generator_loader=load_generator):
        self.master = master
        self.master.title("GAN Image Generator (synthetic images)")

        self.canvas = Canvas(master, width=128, height=128)
        self.canvas.pack()

        self.synthetic_label = tk.Label(master, text=SYNTHETIC_LABEL, fg="red", justify=tk.CENTER)
        self.synthetic_label.pack()

        self.generate_button = tk.Button(master, text="Generate Image", command=self.generate_images)
        self.generate_button.pack()

        self.tk_img = None  # keep a reference so Tk does not discard the image
        self.generator = None
        try:
            self.generator = generator_loader(weights_path)
        except FileNotFoundError:
            self._fail(f"Generator weights file not found:\n{weights_path}\n\n"
                       "Train the model first (python model_training.py) or pass --weights.")
        except Exception as e:
            self._fail(f"Could not load generator weights from:\n{weights_path}\n\n{type(e).__name__}: {e}")

    def _fail(self, message):
        self.generate_button.config(state=tk.DISABLED)
        messagebox.showerror("Weights not available", message, parent=self.master)

    def generate_images(self):
        if self.generator is None:
            return
        random_noise = tf.random.normal([1, NOISE_DIM])
        generated_images = self.generator(random_noise, training=False)
        img = to_uint8_image(generated_images.numpy())
        pil_img = Image.fromarray(img)
        self.tk_img = ImageTk.PhotoImage(image=pil_img)
        self.canvas.delete("all")
        self.canvas.create_image(0, 0, anchor=tk.NW, image=self.tk_img)


def parse_args(argv=None):
    parser = argparse.ArgumentParser(description="Show synthetic images from a trained generator.")
    parser.add_argument("--weights", default=DEFAULT_WEIGHTS,
                        help=f"generator weights file (default: {DEFAULT_WEIGHTS})")
    return parser.parse_args(argv)


if __name__ == "__main__":
    args = parse_args()
    root = tk.Tk()
    app = ImageGeneratorApp(root, weights_path=args.weights)
    root.mainloop()
